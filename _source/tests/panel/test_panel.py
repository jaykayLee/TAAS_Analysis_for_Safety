import asyncio, json
from playwright.async_api import async_playwright
SP = __import__("os").environ.get("CHARTJS_DIR", str(__import__("pathlib").Path(__file__).resolve().parents[3]))
PANEL=(__import__('pathlib').Path(__file__).resolve().parents[3]/'04_Libraries'/'02_Statistics'/'LIB-TAAS'/'build'/'panel.html').as_uri()
OUT='out/t_'
async def legend(pg): return (await pg.inner_text('#legend')).replace('\n',' | ')
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
        ctx=await b.new_context(viewport={'width':1440,'height':950},accept_downloads=True)
        pg=await ctx.new_page()
        await pg.route('**/chart.umd.min.js',lambda r: r.fulfill(path=SP+'/node_modules/chart.js/dist/chart.umd.js',content_type='text/javascript'))
        await pg.route('**/fonts.googleapis.com/**',lambda r: r.fulfill(body='',content_type='text/css'))
        errs=[]; pg.on('pageerror',lambda e: errs.append(str(e))); pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
        await pg.goto(PANEL); await pg.wait_for_timeout(2500)
        print('HEADER:', await pg.inner_text('#libstat'))
        # OECD
        await pg.fill('#q','OECD 국가 교통사고 비교'); await pg.wait_for_timeout(300); await pg.click('button.item'); await pg.wait_for_timeout(1200)
        print('OECD default legend:', await legend(pg))
        print('OECD dims:', [x[:60] for x in await pg.eval_on_selector_all('.dimbox','els=>els.map(e=>e.innerText.replace(/\\n/g," "))')])
        await pg.click('.dimbox [data-a=none]'); await pg.wait_for_timeout(300)
        await pg.click('.chip:has-text("대한민국")'); await pg.click('.chip:has-text("일본")'); await pg.wait_for_timeout(400)
        print('after 해제+대한민국+일본:', await legend(pg), '| tbl cols', await pg.evaluate("document.querySelectorAll('#tbl thead th').length"))
        await pg.screenshot(path=OUT+'oecd.png')
        # 자동 적용 끄고 연도 변경 → 대기 → 실행
        await pg.uncheck('#autoRun'); await pg.fill('#y0','2015'); await pg.wait_for_timeout(600)
        print('pending btn:', await pg.inner_text('#btnRun'), '| rows', await pg.evaluate("document.querySelectorAll('#tbl tbody tr').length"))
        await pg.click('#btnRun'); await pg.wait_for_timeout(400)
        print('after run btn:', await pg.inner_text('#btnRun'), '| rows', await pg.evaluate("document.querySelectorAll('#tbl tbody tr').length"))
        await pg.check('#autoRun')
        # 월별·요일별: 칩 끄면 바로 반영되는지
        await pg.fill('#q','월별·요일별'); await pg.wait_for_timeout(300); await pg.click('button.item'); await pg.wait_for_timeout(1000)
        print('월별 legend:', await legend(pg))
        await pg.click('.chip:has-text("01월")'); await pg.wait_for_timeout(300)
        print('01월 off legend:', await legend(pg))
        await pg.fill('#q','')
        # 그래프 조작: 클릭(M1), ctrl+클릭(M2), 드래그 확대, 메모, ctrl+우클릭 원복
        box=await (await pg.query_selector('#chart')).bounding_box()
        ca=await pg.evaluate("(()=>{const a=Chart.getChart(document.querySelector('#chart')).chartArea;return [a.left,a.top,a.right,a.bottom]})()")
        X=lambda f: box['x']+ca[0]+(ca[2]-ca[0])*f; Y=lambda f: box['y']+ca[1]+(ca[3]-ca[1])*f
        await pg.mouse.click(X(0.30),Y(0.4)); await pg.wait_for_timeout(400)
        await pg.keyboard.down('Control'); await pg.mouse.click(X(0.75),Y(0.4)); await pg.keyboard.up('Control'); await pg.wait_for_timeout(400)
        print('marker bar:', (await pg.inner_text('#mbar'))[:300].replace('\n',' | '))
        await pg.screenshot(path=OUT+'markers.png')
        await pg.mouse.move(X(0.1),Y(0.5)); await pg.mouse.down(); await pg.mouse.move(X(0.3),Y(0.5),steps=6); await pg.mouse.move(X(0.45),Y(0.5),steps=6); await pg.mouse.up(); await pg.wait_for_timeout(400)
        print('zoom x:', await pg.evaluate("(()=>{const c=Chart.getChart(document.querySelector('#chart'));return [c.scales.x.min,c.scales.x.max,c.data.labels.length,c.scales.y.min,c.scales.y.max]})()"))
        await pg.mouse.dblclick(X(0.5),Y(0.3)); await pg.wait_for_timeout(300); await pg.keyboard.type('메모 시험'); await pg.mouse.click(box['x']+5,box['y']-30); await pg.wait_for_timeout(300)
        print('notes:', await pg.evaluate("[...document.querySelectorAll('#cbox .memo')].map(e=>[e.innerText,e.style.display])"))
        await pg.screenshot(path=OUT+'zoom.png')
        await pg.keyboard.down('Control'); await pg.mouse.click(X(0.5),Y(0.5),button='right'); await pg.keyboard.up('Control'); await pg.wait_for_timeout(300)
        print('after reset:', await pg.evaluate("(()=>{const c=Chart.getChart(document.querySelector('#chart'));return [c.scales.x.min,c.scales.x.max]})()"))
        async with pg.expect_download() as d: await pg.click('.ctools[data-for=main] [data-act=png]')
        dl=await d.value; print('png:', dl.suggested_filename)
        # 사이드바 접기/너비
        await pg.click('#btnSide'); await pg.wait_for_timeout(300)
        print('collapsed:', await pg.evaluate("document.querySelector('.main').classList.contains('collapsed')"), (await (await pg.query_selector('#side')).bounding_box())['width'])
        await pg.click('#btnSide'); await pg.wait_for_timeout(200)
        rz=await (await pg.query_selector('#resizer')).bounding_box()
        await pg.mouse.move(rz['x']+3,rz['y']+300); await pg.mouse.down(); await pg.mouse.move(rz['x']+163,rz['y']+300,steps=8); await pg.mouse.up(); await pg.wait_for_timeout(200)
        print('side width after drag:', (await (await pg.query_selector('#side')).bounding_box())['width'], '| list scrollWidth>client:', await pg.evaluate("(()=>{const l=document.querySelector('.tree .list');return [l.scrollWidth,l.clientWidth]})()"))
        await pg.mouse.move(rz['x']+163,rz['y']+300); await pg.mouse.down(); await pg.mouse.move(rz['x']-80,rz['y']+300,steps=8); await pg.mouse.up(); await pg.wait_for_timeout(200)
        print('narrow:', (await (await pg.query_selector('#side')).bounding_box())['width'], await pg.evaluate("(()=>{const l=document.querySelector('.tree .list');return [l.scrollWidth,l.clientWidth]})()"))
        await pg.screenshot(path=OUT+'side.png')
        # 상관분석 산점도
        await pg.click('#tab-tech'); await pg.wait_for_timeout(400)
        for i in (0,5):
            cards=await pg.query_selector_all('.tech'); bt=await cards[i].query_selector_all('button'); await bt[1].click(); await pg.wait_for_timeout(1200); await pg.click('#tab-tech'); await pg.wait_for_timeout(300)
        await pg.click('#tab-corr'); await pg.wait_for_timeout(800)
        sb=await (await pg.query_selector('#scatter')).bounding_box()
        pts=await pg.evaluate("(()=>{const c=Chart.getChart(document.querySelector('#scatter'));return c.getDatasetMeta(0).data.slice(0,6).map(e=>[e.x,e.y])})()")
        await pg.mouse.click(sb['x']+pts[0][0]+3,sb['y']+pts[0][1]+2); await pg.wait_for_timeout(400)
        await pg.keyboard.down('Control'); await pg.mouse.click(sb['x']+pts[3][0],sb['y']+pts[3][1]); await pg.keyboard.up('Control'); await pg.wait_for_timeout(400)
        print('scatter bar:', (await pg.inner_text('#sbar')).replace('\n',' | ')[:300])
        await pg.evaluate("document.querySelector('#scatter').scrollIntoView()"); await pg.wait_for_timeout(200)
        await pg.screenshot(path=OUT+'scatter.png')
        print('errors', errs)
        await b.close()
asyncio.run(main())
